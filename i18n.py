def tr(lang: str, key: str, **kwargs: str) -> str:
    """Return translated string for language code ('fa', 'en', 'zh')."""
    table = TRANSLATIONS.get(lang, TRANSLATIONS["fa"])
    text = table.get(key, TRANSLATIONS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text
